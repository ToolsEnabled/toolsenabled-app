#!/usr/bin/env node
/* THE ONE-TIME WIRE-IN, ON THE OWNER'S OWN INSTALLATION.
 *
 * Everything else in this lane runs against a sterile profile, because a
 * harness that writes into the real installation is a harness that can damage
 * it. This one is the exception and it says so: R1235 gate 2 is "the owner can
 * open the installed product, sign in as himself, and see his own data and his
 * own card on file", and no sterile profile can prove that. So this runs
 * against `%APPDATA%\ToolsEnabled`, once, on purpose.
 *
 * WHAT IT WILL NOT DO, and these are the rails:
 *   - It NEVER types a password. It fills the name fields, and then it WAITS
 *     for the owner to choose the secret and press the shipped button. A local
 *     account has no reset by design; a password generated by an agent and
 *     handed over is a password that can go missing, and the account is then
 *     unrecoverable. So the secret is his, chosen at his keyboard, and it
 *     passes through no log, no dialog, no report and no argument.
 *   - It NEVER reads, decrypts, copies, moves or prints a vault record. The
 *     attachment writes a KEY NAME.
 *   - It NEVER charges, orders, reserves or authorizes anything. There is no
 *     code path from this file to one.
 *   - It creates NO account itself. If the owner does not press the button,
 *     nothing is created and the run reports that honestly.
 *
 * IT REFUSES ON A COMPUTER THAT ALREADY HAS AN ACCOUNT. This exists to make the
 * first one. A second run must not sit there filling a form over somebody's
 * signed-in window; `--force` is deliberately not implemented.
 *
 * `--dry-run` does everything except launch: it prints what it would do and
 * what it found, which is how you check the rails without a window opening on
 * the owner's screen.
 */
import { spawn } from 'node:child_process'
import { cpSync, existsSync, mkdtempSync, readFileSync, readdirSync, rmSync } from 'node:fs'
import { createRequire } from 'node:module'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { assertRendererMeasurable, assertStagedRendererConsistent } from './lib/staged-renderer.mjs'

const require_ = createRequire(import.meta.url)
const SELF = fileURLToPath(import.meta.url)
const REPO_ROOT = path.resolve(path.dirname(SELF), '..')
const RELEASE = path.join(REPO_ROOT, 'release', 'win-unpacked')
const REAL_USER_DATA = path.join(process.env.APPDATA || '', 'ToolsEnabled')
const CARD_KEY = 'payment_card_default'
const delay = ms => new Promise(resolve => setTimeout(resolve, ms))

const argv = new Set(process.argv.slice(2))
const DRY_RUN = argv.has('--dry-run')
const USERNAME = 'josh'
const DISPLAY_NAME = 'Josh'
/* How long the window stays open waiting for him to choose a password. Bounded,
   because an unattended window left open forever is its own problem. */
const WAIT_FOR_OWNER_MS = 15 * 60 * 1000

const results = []
function check(name, pass, detail = '') {
  results.push({ name, pass, detail })
  console.log(`${pass ? '  ok  ' : '  FAIL'} ${name}${detail ? `  ${detail}` : ''}`)
}
function note(text) { console.log(`  --   ${text}`) }

function appExecutable(appRoot) {
  const executables = readdirSync(appRoot).filter(entry => entry.toLowerCase().endsWith('.exe'))
  if (executables.length === 1) return path.join(appRoot, executables[0])
  const launcher = executables.find(entry => !/^(elevate|squirrel|crashpad)/i.test(entry))
  if (!launcher) throw new Error(`cannot tell which of these is the launcher: ${executables.join(', ')}`)
  return path.join(appRoot, launcher)
}

/* The packaged artifact with this tree's renderer, shell and vault tooling in
   it -- which is what the next `npm run dist` produces. The shipped
   release/win-unpacked is missing resources/capability/tools/lib/, so its
   secrets.ps1 cannot even start; see the lane report. Running the owner's
   installation against an artifact that cannot read its own vault would prove
   nothing about his card. */
async function stage(scratch) {
  /* THE RENDERER THIS RUN IS ABOUT TO MEASURE MUST BE THE ONE THE SOURCE SAYS.
     Shared with every other dist/-staging harness (tools/lib/staged-renderer.mjs);
     refuses with exit 2 and both timestamps rather than reporting a stale bundle
     as a defect in the product. */
  assertRendererMeasurable({ repoRoot: REPO_ROOT, sourceDist: path.join(REPO_ROOT, 'dist') })
  const asar = require_(path.join(REPO_ROOT, 'node_modules', '@electron', 'asar'))
  const app = path.join(scratch, 'app')
  const unpacked = path.join(scratch, 'asar-stage')
  if (!existsSync(path.join(RELEASE, 'resources', 'app.asar'))) {
    throw new Error(`no packaged build at ${RELEASE}`)
  }
  cpSync(RELEASE, app, { recursive: true, dereference: true })
  asar.extractAll(path.join(app, 'resources', 'app.asar'), unpacked)
  for (const directory of ['dist', 'shell']) {
    rmSync(path.join(unpacked, directory), { recursive: true, force: true })
    cpSync(path.join(REPO_ROOT, directory), path.join(unpacked, directory), { recursive: true })
  }
  /* ...and the COPY of it must have arrived whole; see the module header for the
     blank-stage, no-exception symptom a torn copy produces. */
  assertStagedRendererConsistent({
    stagedDist: path.join(unpacked, 'dist'),
    sourceDist: path.join(REPO_ROOT, 'dist'),
  })
  cpSync(path.join(REPO_ROOT, 'package.json'), path.join(unpacked, 'package.json'))
  await asar.createPackage(unpacked, path.join(app, 'resources', 'app.asar'))
  for (const entry of ['secrets.ps1', 'lib']) {
    const from = path.join(REPO_ROOT, 'capability', 'tools', entry)
    const to = path.join(app, 'resources', 'capability', 'tools', entry)
    if (existsSync(from)) cpSync(from, to, { recursive: true })
  }
  return appExecutable(app)
}

async function freePort() {
  const net = await import('node:net')
  return new Promise((resolve, reject) => {
    const server = net.createServer()
    server.once('error', reject)
    server.listen(0, '127.0.0.1', () => {
      const { port } = server.address()
      server.close(() => resolve(port))
    })
  })
}

function createSession(port, child) {
  let socket = null
  let nextId = 1
  const pending = new Map()
  return {
    async open() {
      for (let attempt = 0; attempt < 180; attempt += 1) {
        if (child.exitCode !== null) throw new Error(`the app exited with code ${child.exitCode} before the debugger answered`)
        try {
          const response = await fetch(`http://127.0.0.1:${port}/json/list`)
          const page = (await response.json()).find(entry => entry.type === 'page' && entry.webSocketDebuggerUrl)
          if (page) {
            socket = new WebSocket(page.webSocketDebuggerUrl)
            await new Promise((resolve, reject) => {
              socket.addEventListener('open', resolve, { once: true })
              socket.addEventListener('error', reject, { once: true })
            })
            socket.addEventListener('message', event => {
              const packet = JSON.parse(event.data)
              const handler = pending.get(packet.id)
              if (handler) { pending.delete(packet.id); handler(packet) }
            })
            return
          }
        } catch { /* not listening yet */ }
        await delay(500)
      }
      throw new Error('no debuggable page appeared within 90s')
    },
    send(method, params = {}) {
      const id = nextId++
      socket.send(JSON.stringify({ id, method, params }))
      return new Promise(resolve => pending.set(id, resolve))
    },
    close() { try { socket?.close() } catch { /* already gone */ } },
  }
}

const VISIBLE = `(selector) => {
  const node = document.querySelector(selector)
  if (!node) return { state: 'absent' }
  const box = node.getBoundingClientRect()
  const style = getComputedStyle(node)
  if (style.display === 'none' || style.visibility === 'hidden' || Number(style.opacity) === 0) return { state: 'hidden' }
  if (box.width < 1 || box.height < 1) return { state: 'zero-size' }
  return { state: 'visible', x: box.x + box.width / 2, y: box.y + box.height / 2 }
}`

const READ_SCREEN = `() => {
  const payment = document.querySelector('[data-account-data-payment]')
  const text = selector => {
    const node = document.querySelector(selector)
    return node ? node.textContent.replace(/\\s+/g, ' ').trim() : null
  }
  return {
    route: document.body.dataset.route || null,
    title: text('.setup-title'),
    settings: text('[data-account-data-settings]'),
    history: text('[data-account-data-history]'),
    payment: payment ? payment.textContent.replace(/\\s+/g, ' ').trim() : null,
    paymentState: payment ? payment.dataset.paymentState : null,
  }
}`

async function main() {
  const startedAt = Date.now()

  /* NOT A QA DRIVER, AND DELIBERATELY NOT NAMED LIKE ONE.
   *
   * This started life as `owner-account-live-wire-in-qa.mjs`, which
   * tools/packaged-qa-suite.mjs discovers by the `-qa.mjs` convention -- and
   * that was wrong twice over. It opens a VISIBLE window on the owner's own
   * profile and then waits a quarter of an hour for him to type, which a
   * nightly suite must never do; and the suite's own guard (test 4 of
   * tools/test/packaged-qa-suite.test.mjs) forbids `windowsHide: false` in any
   * driver, correctly, because a driver that steals focus is a driver nobody
   * can run unattended. Renaming it out of discovery is the honest fix. Making
   * the literal unmatchable to slip past the guard would have been the other
   * kind.
   *
   * The `--live` gate stays anyway: running this by hand without meaning to is
   * still a window on his screen. */
  if (!argv.has('--live') && !DRY_RUN) {
    console.log('held back: this harness drives the OWNER\'S OWN installation and waits for him to')
    console.log('choose a password at the keyboard. Run it with --live when he is there, or')
    console.log('--dry-run to see what it would do.')
    return
  }

  console.log(`the owner's installation: ${REAL_USER_DATA}`)
  const accountsFile = path.join(REAL_USER_DATA, 'product-accounts.json')
  if (existsSync(accountsFile)) {
    check('this computer has no account yet', false, `${accountsFile} already exists; this run makes the FIRST one and refuses to touch an existing one`)
    process.exitCode = 1
    return
  }
  check('this computer has no account yet', true, 'product-accounts.json is absent')
  /* VISIBLE, because he has to see it and type into it. Every other harness in
     this lane runs hidden; this one cannot. */
  note('the window will be VISIBLE. He types the password; this file never does.')

  if (DRY_RUN) {
    note(`would fill username=${USERNAME} displayName=${DISPLAY_NAME} and then WAIT up to ${Math.round(WAIT_FOR_OWNER_MS / 60000)} minutes`)
    note(`would then attach vault key ${CARD_KEY} by name -- no read, no decrypt, no charge`)
    console.log('\ndry run: nothing was launched and nothing was changed')
    return
  }

  const scratch = mkdtempSync(path.join(os.tmpdir(), 'owner-account-live-'))
  let child = null
  let session = null
  try {
    const executable = await stage(scratch)
    const port = await freePort()
    const environment = { ...process.env }
    delete environment.ELECTRON_RUN_AS_NODE
    delete environment.ELECTRON_NO_ATTACH_CONSOLE
    delete environment.TOOLSENABLED_VAULT_PATH
    delete environment.TOOLSENABLED_STATE_ROOT
    /* NO --user-data-dir. That is the whole point: this runs on his profile. */
    child = spawn(executable, [`--remote-debugging-port=${port}`], {
      env: environment, windowsHide: false, stdio: ['ignore', 'pipe', 'pipe'],
    })
    session = createSession(port, child)
    await session.open()
    const evaluate = async expression => {
      const packet = await session.send('Runtime.evaluate', { expression, returnByValue: true, awaitPromise: true })
      return packet?.result?.result?.value
    }
    const clickVisible = async selector => {
      const spot = await evaluate(`(${VISIBLE})(${JSON.stringify(selector)})`)
      if (spot?.state !== 'visible') return spot?.state || 'absent'
      for (const type of ['mousePressed', 'mouseReleased']) {
        await session.send('Input.dispatchMouseEvent', { type, x: spot.x, y: spot.y, button: 'left', clickCount: 1 })
      }
      await delay(450)
      return 'clicked'
    }
    const typeInto = async (selector, value) => {
      const spot = await evaluate(`(${VISIBLE})(${JSON.stringify(selector)})`)
      if (spot?.state !== 'visible') return spot?.state || 'absent'
      for (const type of ['mousePressed', 'mouseReleased']) {
        await session.send('Input.dispatchMouseEvent', { type, x: spot.x, y: spot.y, button: 'left', clickCount: 1 })
      }
      await session.send('Input.insertText', { text: value })
      await delay(150)
      return 'typed'
    }

    await delay(2500)
    await evaluate("location.hash = '#/account'")
    await delay(1500)
    check('the sign-in screen is open on his installation', (await evaluate('document.body.dataset.route')) === 'account')

    await clickVisible('[data-account-mode="create"]')
    await delay(400)
    const typedName = await typeInto('[data-account-form="create"] input[name="username"]', USERNAME)
    const typedDisplay = await typeInto('[data-account-form="create"] input[name="displayName"]', DISPLAY_NAME)
    check('his name is filled in, the password field is left for him', typedName === 'typed' && typedDisplay === 'typed',
      `${typedName}/${typedDisplay}`)
    /* Focus the field he has to fill, so the cursor is already where he needs
       it when he looks at the window. */
    await clickVisible('[data-account-form="create"] input[name="password"]')

    console.log('\n  WAITING for the owner to type a password and press "Create account".')
    console.log(`  Up to ${Math.round(WAIT_FOR_OWNER_MS / 60000)} minutes. Nothing here types it.\n`)

    const deadline = Date.now() + WAIT_FOR_OWNER_MS
    let created = false
    while (Date.now() < deadline) {
      await delay(3000)
      if (existsSync(accountsFile)) { created = true; break }
      if (child.exitCode !== null) break
    }
    check('he created the account through the shipped form', created,
      created ? 'product-accounts.json now exists' : 'no account was created; nothing was changed')
    if (!created) return

    await delay(2500)
    const signedIn = await evaluate('window.mcAccount.current().then(state => state && state.signedIn === true ? state.account.id : null)')
    check('and the window has him signed in', /^[0-9a-f]{32}$/.test(String(signedIn || '')), String(signedIn).slice(0, 8) + '...')

    /* THE WIRE-IN. A key name, written down. Nothing is read and nothing moves. */
    const attached = await evaluate(`window.mcAccount.attachPaymentMethod({ vaultKey: ${JSON.stringify(CARD_KEY)}, note: 'R1235 one-time wire-in' }).then(r => r.ok === true)`)
    check(`his existing vault record is attached to his account by key name (${CARD_KEY})`, attached === true, String(attached))

    await evaluate("location.hash = '#/'")
    await delay(500)
    await evaluate("location.hash = '#/account'")
    await delay(3000)
    const screen = await evaluate(`(${READ_SCREEN})()`)
    check('he can see his own settings on the screen', typeof screen.settings === 'string' && screen.settings.length > 0, (screen.settings || 'absent').slice(0, 100))
    check('he can see his own history on the screen', typeof screen.history === 'string' && screen.history.length > 0, (screen.history || 'absent').slice(0, 100))
    check('he can see his own card on the screen', screen.paymentState === 'on-file', `state=${screen.paymentState}`)
    note(screen.payment || 'no payment row rendered')
    console.log('\n  The window is left OPEN and signed in, for him.')
  } catch (error) {
    check('the run completed', false, error?.message || String(error))
  } finally {
    try { session?.close() } catch { /* already gone */ }
    /* The child is NOT killed. It is his window, he is signed in to it, and
       taking it away the moment this finishes would be the opposite of the
       point. The scratch copy of the artifact stays on disk while it runs. */
  }

  const failed = results.filter(entry => !entry.pass)
  console.log(`\n${results.length - failed.length}/${results.length} checks passed in ${Math.round((Date.now() - startedAt) / 1000)}s`)
  process.exitCode = failed.length === 0 ? 0 : 1
}

main()
