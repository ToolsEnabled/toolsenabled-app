import fs from 'node:fs'
import path from 'node:path'
import { createHash } from 'node:crypto'

const sha = bytes => createHash('sha256').update(bytes).digest('hex')
const relativePath = value => typeof value === 'string' && value.length < 512 && /^[A-Za-z0-9@_./+ -]+$/.test(value)
  && !path.isAbsolute(value) && !value.split('/').some(part => !part || part === '.' || part === '..' || /[. ]$/.test(part))

function plainPath(root, relative) {
  if (!relativePath(relative)) throw Error('invalid provider runtime path')
  let current = path.resolve(root)
  if (fs.lstatSync(current).isSymbolicLink()) throw Error('linked provider runtime root')
  for (const part of relative.split('/')) {
    current = path.join(current, part)
    if (fs.lstatSync(current).isSymbolicLink()) throw Error('linked provider runtime path')
  }
  return current
}

export function readPinnedRuntimeFile(root, relative, pin) {
  const file = plainPath(root, relative)
  const stat = fs.statSync(file)
  if (!stat.isFile() || stat.size !== pin.bytes) throw Error(`provider runtime byte count changed: ${relative}`)
  const bytes = fs.readFileSync(file)
  if (bytes.length !== pin.bytes || sha(bytes) !== pin.sha256) throw Error(`provider runtime hash changed: ${relative}`)
  return bytes
}

// Vendored generated bytes and their per-file manifest are committed together.
// There is no unrestricted node_modules/vendor prefix in the shipping boundary.
export function collectProviderRuntimePayload(source, declarations = []) {
  if (!Array.isArray(declarations) || declarations.length > 8) throw Error('invalid provider runtime declarations')
  const pins = new Map(), records = [], identities = new Set()
  for (const declaration of declarations) {
    const { id, manifest: manifestPath } = declaration || {}
    if (!/^[a-z][a-z0-9-]{0,63}$/.test(id || '') || identities.has(id)
      || manifestPath !== `config/${id}-runtime.json`) throw Error('invalid provider runtime declaration')
    identities.add(id)
    const manifestBytes = fs.readFileSync(plainPath(source, manifestPath))
    if (manifestBytes.length > 2 * 1024 * 1024) throw Error('provider runtime manifest too large')
    const manifest = JSON.parse(manifestBytes)
    const runtimePath = `provider-runtimes/${id}`
    if (manifest.schemaVersion !== 1 || manifest.id !== id || manifest.runtimePath !== runtimePath
      || typeof manifest.version !== 'string' || !/^\d+\.\d+\.\d+$/.test(manifest.version)
      || !manifest.files || Array.isArray(manifest.files) || typeof manifest.files !== 'object'
      || !relativePath(manifest.entrypoint) || !Object.hasOwn(manifest.files, manifest.entrypoint)) throw Error('invalid provider runtime manifest')
    const entries = Object.entries(manifest.files)
    if (!entries.length || entries.length > 5000) throw Error('provider runtime file count exceeds bound')
    let byteCount = 0
    for (const [relative, pin] of entries) {
      if (!relativePath(relative) || !pin || !/^[a-f0-9]{64}$/.test(pin.sha256)
        || !Number.isSafeInteger(pin.bytes) || pin.bytes < 0 || pin.bytes > 64 * 1024 * 1024) throw Error('invalid provider runtime file pin')
      byteCount += pin.bytes
      if (byteCount > 128 * 1024 * 1024) throw Error('provider runtime size exceeds bound')
      const full = `${runtimePath}/${relative}`
      readPinnedRuntimeFile(source, full, pin)
      pins.set(full, Object.freeze({ ...pin }))
    }
    // Reject undeclared extras as well as missing or changed bytes. Every node
    // is inspected before descent so directory links cannot escape the root.
    const actual = [], pending = ['']
    while (pending.length) {
      const relative = pending.pop()
      const directory = plainPath(source, runtimePath + (relative ? `/${relative}` : ''))
      for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
        const child = relative ? `${relative}/${entry.name}` : entry.name
        if (entry.isSymbolicLink()) throw Error('linked provider runtime path')
        if (entry.isDirectory()) pending.push(child)
        else if (entry.isFile()) actual.push(child)
        else throw Error('unsupported provider runtime node')
        if (actual.length + pending.length > 10000) throw Error('provider runtime inventory exceeds bound')
      }
    }
    if (actual.sort().join('\n') !== entries.map(([file]) => file).sort().join('\n')) throw Error('provider runtime has undeclared files')
    const manifestSha256 = sha(manifestBytes)
    pins.set(manifestPath, { bytes: manifestBytes.length, sha256: manifestSha256 })
    records.push({ id, version: manifest.version, manifest: manifestPath, manifestSha256, runtimePath,
      entrypoint: manifest.entrypoint, fileCount: entries.length, byteCount })
  }
  return { pins, files: [...pins.keys()].sort(), records }
}
