import { createHash } from 'node:crypto'
import { createRequire } from 'node:module'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { resolveCapabilitySourceBinding } from './lib/capability-source-git.mjs'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const options = { check: false }
for (let index = 2; index < process.argv.length; index += 1) {
  const flag = process.argv[index]
  if (flag === '--check') options.check = true
  else if (['--source', '--source-ref'].includes(flag) && process.argv[index + 1]) {
    options[flag === '--source' ? 'source' : 'sourceRef'] = process.argv[++index]
  } else throw new Error(`Unknown or incomplete option: ${flag}`)
}
const { source } = resolveCapabilitySourceBinding({
  repoRoot, explicitSource: options.source, explicitSourceRef: options.sourceRef,
})
const sourceFile = path.join(source, 'src/lib/mission-bridge/api-contract.js')
const sourceText = readFileSync(sourceFile, 'utf8')
const exportLine = /^module\.exports = \{ ([a-zA-Z0-9_, ]+) \};$/gm
const matches = [...sourceText.matchAll(exportLine)]
if (matches.length !== 1 || /\brequire\s*\(|\bprocess\.|\bBuffer\b/.test(sourceText)) {
  throw new Error('The engine API contract is not the expected data-only, browser-portable module.')
}
const digest = createHash('sha256').update(sourceText).digest('hex')
const generated = '// Generated by tools/sync-bridge-api-contract.mjs; do not hand-edit.\n'
  + `// Engine contract SHA-256: ${digest}\n`
  + sourceText.replace(exportLine, 'export { $1 };')
const require = createRequire(import.meta.url)
const { BRIDGE_API_NAME, BRIDGE_API_CONTRACT_SCHEMA } = require(sourceFile)

function ts(schema) {
  if (schema.enum) return schema.enum.map(value => JSON.stringify(value)).join(' | ')
  if (schema.type === 'string') return 'string'
  if (schema.type === 'integer') return 'number'
  if (schema.type === 'array') return `ReadonlyArray<${ts(schema.items)}>`
  if (schema.type === 'object' && schema.additionalProperties === false) {
    return '{ ' + Object.entries(schema.properties).map(([key, child]) =>
      `readonly ${JSON.stringify(key)}${schema.required.includes(key) ? '' : '?'}: ${ts(child)};`,
    ).join(' ') + ' }'
  }
  throw new Error(`Unsupported contract schema type: ${schema.type}`)
}
const artifacts = new Map([
  ['src/generated/bridge-api-contract.js', generated],
  ['src/generated/bridge-api-contract.d.ts',
    '// Generated from the engine API schema; runtime validation additionally checks bounds.\n'
    + `export const BRIDGE_API_NAME: ${JSON.stringify(BRIDGE_API_NAME)};\n`
    + 'export const BRIDGE_API_MAJOR: number;\nexport const BRIDGE_API_MINOR: number;\n'
    + 'export const BRIDGE_API_CONTRACT_SCHEMA: Readonly<Record<string, unknown>>;\n'
    + `export type BridgeApiContract = ${ts(BRIDGE_API_CONTRACT_SCHEMA)};\n`
    + 'export function createBridgeApiContract(routes: Record<string, string>): BridgeApiContract;\n'
    + 'export function validateBridgeApiContract(value: unknown): value is BridgeApiContract;\n'
    + 'export function assessBridgeApiCompatibility(value: unknown, options?: { requiredActions?: string[] }): '
    + '{ ok: true; apiMajor: number; apiMinor: number } | { ok: false; code: string; missingActions?: string[] };\n'],
  ['docs/generated/bridge-api-contract.schema.json', JSON.stringify(BRIDGE_API_CONTRACT_SCHEMA, null, 2) + '\n'],
])
for (const [relative, expected] of artifacts) {
  const target = path.join(repoRoot, relative)
  if (options.check) {
    if (!existsSync(target) || readFileSync(target, 'utf8') !== expected) {
      throw new Error(`Generated API contract is missing or stale: ${relative}`)
    }
  } else {
    mkdirSync(path.dirname(target), { recursive: true })
    writeFileSync(target, expected, 'utf8')
  }
}
console.log(`${options.check ? 'Verified' : 'Generated'} ${artifacts.size} API contract artifacts from ${digest}.`)
