'use strict'
const { app, BrowserWindow, session } = require('electron')
const fs = require('node:fs')
const path = require('node:path')
const { fileURLToPath } = require('node:url')
const data = process.argv[2]
if (!data || !path.isAbsolute(data) || fs.realpathSync.native(data) !== data) throw new Error('A real isolated output directory is required')
app.setName('ToolsEnabled Isolated Empty Role Editor')
for (const key of ['userData', 'sessionData', 'logs', 'crashDumps']) {
  const directory = path.join(data, key); fs.mkdirSync(directory); app.setPath(key, directory)
}
app.disableHardwareAcceleration()
const report = { pageErrors: [], deniedRequests: [] }
let win
app.on('window-all-closed', () => {})
app.whenReady().then(async () => {
  session.defaultSession.webRequest.onBeforeRequest((details, callback) => {
    const allowed = details.url.startsWith('data:') || (details.url.startsWith('file:') && path.dirname(fileURLToPath(details.url)) === data)
    if (!allowed) report.deniedRequests.push(details.url)
    callback({ cancel: !allowed })
  })
  win = new BrowserWindow({ show: false, width: 1280, height: 900, useContentSize: true,
    webPreferences: { sandbox: true, contextIsolation: true, nodeIntegration: false, offscreen: true, backgroundThrottling: false } })
  win.webContents.setWindowOpenHandler(() => ({ action: 'deny' }))
  win.webContents.on('console-message', details => { if (details.level === 'error') report.pageErrors.push(details.message) })
  await win.loadFile(path.join(data, 'index.html'))
  const evaluate = code => win.webContents.executeJavaScript(code, true)
  const settle = () => evaluate('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))')
  const click = async selector => {
    const point = await evaluate(`emptyRoleEditor.point(${JSON.stringify(selector)})`)
    win.webContents.sendInputEvent({ type: 'mouseMove', ...point })
    win.webContents.sendInputEvent({ type: 'mouseDown', button: 'left', clickCount: 1, ...point })
    win.webContents.sendInputEvent({ type: 'mouseUp', button: 'left', clickCount: 1, ...point })
    await settle()
  }
  const write = async (field, text) => {
    await click(`[data-field="${field}"]`)
    win.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'A', modifiers: [process.platform === 'darwin' ? 'meta' : 'control'] })
    win.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'A', modifiers: [process.platform === 'darwin' ? 'meta' : 'control'] })
    win.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Backspace' })
    win.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Backspace' })
    if (text) await win.webContents.insertText(text)
    await settle()
  }
  await click('[data-open-studio]')
  report.canvasStatus = await evaluate('emptyRoleEditor.status()')
  await click('[data-select-role="empty-helper"]')
  report.selectedStatus = await evaluate('emptyRoleEditor.status()')
  report.loaded = await evaluate('emptyRoleEditor.fields()')
  await write('owns', 'Temporary responsibility.')
  await write('owns', '')
  await click('[data-action="save"]')
  report.editStatus = await evaluate('emptyRoleEditor.status()')
  report.afterEdit = await evaluate('emptyRoleEditor.fields()')
  await click('[data-tab="functions"]')
  report.savedAfterTab = await evaluate('emptyRoleEditor.status()')
  await click('[data-select-role="empty-helper"]')
  report.savedAfterSameSelection = await evaluate('emptyRoleEditor.status()')
  await click('[data-action="close"]')
  report.closedStatus = await evaluate('emptyRoleEditor.outsideStatus()')
  await click('[data-open-studio]')
  report.savedAfterReopen = await evaluate('emptyRoleEditor.status()')
  await click('[data-action="new"]')
  report.newDraftStatus = await evaluate('emptyRoleEditor.status()')
  await write('id', 'new-empty-helper')
  await click('[data-action="save"]')
  report.createStatus = await evaluate('emptyRoleEditor.status()')
  report.afterCreate = await evaluate('emptyRoleEditor.fields()')
  await click('[data-tab="functions"]')
  report.createdAfterTab = await evaluate('emptyRoleEditor.status()')
  await click('[data-tab="directions"]')
  await write('owns', 'Refused responsibility.')
  await click('[data-action="save"]')
  report.refusedStatus = await evaluate('emptyRoleEditor.status()')
  await click('[data-tab="functions"]')
  report.refusedAfterTab = await evaluate('emptyRoleEditor.status()')
  await click('[data-action="close"]')
  await click('[data-open-studio]')
  report.refusedAfterReopen = await evaluate('emptyRoleEditor.status()')
  await click('[data-tab="directions"]')
  report.refusedDraft = await evaluate('emptyRoleEditor.fields()')
  await click('[data-action="canvas"]')
  report.returnedCanvasStatus = await evaluate('emptyRoleEditor.status()')
  await click('[data-select-role="new-empty-helper"]')
  report.reselectedStatus = await evaluate('emptyRoleEditor.status()')
  report.operations = await evaluate('emptyRoleEditor.operations()')
  report.roles = await evaluate('emptyRoleEditor.roles()')
  report.visible = win.isVisible()
  win.destroy(); report.destroyed = win.isDestroyed()
  fs.writeFileSync(path.join(data, 'observations.json'), JSON.stringify(report, null, 2) + '\n')
  app.exit(0)
}).catch(error => {
  report.failure = { message: error.message, stack: error.stack }
  fs.writeFileSync(path.join(data, 'observations.json'), JSON.stringify(report, null, 2) + '\n')
  if (win && !win.isDestroyed()) win.destroy()
  app.exit(1)
})
