'use strict'
const { app, BrowserWindow, screen, desktopCapturer, globalShortcut, ipcMain } = require('electron')
const assert = require('node:assert/strict')
const path = require('node:path')
const fs = require('node:fs')
const { createScreenControlAdapter } = require('../../../shell/screen-control-adapter.cjs')
const { createScreenControlIndicator } = require('../../../shell/screen-control-indicator.cjs')
const dataRoot = process.argv[2]
if (!dataRoot || !path.isAbsolute(dataRoot)) throw new Error('An isolated user-data directory is required.')
app.setPath('userData', dataRoot)
app.commandLine.appendSwitch('disable-gpu')
let window
async function run() {
  await app.whenReady()
  window = new BrowserWindow({ x: 100, y: 100, width: 800, height: 600, frame: false, show: true,
    webPreferences: { sandbox: true, contextIsolation: true, nodeIntegration: false } })
  await window.loadURL('data:text/html,' + encodeURIComponent('<style>body{margin:40px;font:20px sans-serif}input,button{padding:12px;font:20px sans-serif}</style><h1>Isolated screen-control fixture</h1><input id="text" aria-label="Test text"><button id="save" onclick="this.textContent=\'Saved\'">Save</button><p>Mouse and keyboard input is confined to this test desktop.</p>'))
  window.focus()
  const adapter = createScreenControlAdapter({ screen, desktopCapturer })
  assert.equal(adapter.supported(), true)
  const control = input => adapter.execute(adapter.validate(input), new AbortController().signal)
  const targets = await window.webContents.executeJavaScript(`Object.fromEntries(['text','save'].map(id=>{const r=document.getElementById(id).getBoundingClientRect();return [id,{x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)}]}))`)
  const bounds = window.getBounds()
  const point = name => ({ x: targets[name].x + bounds.x, y: targets[name].y + bounds.y })
  await control({ action: 'click', ...point('text') })
  await control({ action: 'type', text: 'Agent café λ' })
  assert.equal(await window.webContents.executeJavaScript('document.getElementById("text").value'), 'Agent café λ')
  await control({ action: 'key', key: 'Control+A' })
  await control({ action: 'type', text: 'Replacement' })
  assert.equal(await window.webContents.executeJavaScript('document.getElementById("text").value'), 'Replacement')
  await control({ action: 'click', ...point('save') })
  assert.equal(await window.webContents.executeJavaScript('document.getElementById("save").textContent'), 'Saved')
  assert.deepEqual(screen.getCursorScreenPoint(), point('save'))
  const image = await control({ action: 'screenshot' })
  assert.ok(image.__mcpImage.length > 100)
  assert.ok(image.__mcpImage.length <= 1024 * 1024)
  fs.writeFileSync(path.join(dataRoot, 'screen-control.png'), image.__mcpImage)
  let stopped = 0
  const indicator = createScreenControlIndicator({ BrowserWindow, screen, globalShortcut, ipcMain })
  const stop = () => { stopped++; indicator.hide() }
  try {
    await Promise.all([indicator.ready(stop), indicator.ready(stop)])
    assert.equal(BrowserWindow.getAllWindows().length, 3, 'concurrent grants share one indicator')
    indicator.show({ label: 'Fixture agent', moving: true })
    const bar = BrowserWindow.getAllWindows().find(item => item.getBounds().width === 360)
    const halo = BrowserWindow.getAllWindows().find(item => item.getBounds().width === 76)
    assert.equal(bar.isVisible(), true); assert.equal(halo.isVisible(), true)
    await control({ action: 'click', ...point('text') })
    await control({ action: 'key', key: 'Control+A' })
    await control({ action: 'type', text: 'Pointer overlay is click-through' })
    assert.equal(await window.webContents.executeJavaScript('document.getElementById("text").value'), 'Pointer overlay is click-through')
    const stopButton = await bar.webContents.executeJavaScript('(()=>{const r=document.querySelector("button").getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)}})()')
    await control({ action: 'click', x: bar.getBounds().x + stopButton.x, y: bar.getBounds().y + stopButton.y })
    await new Promise(resolve => setTimeout(resolve, 100))
    assert.equal(stopped, 1, 'the visible Stop all button stops access')
    indicator.show({ label: 'Fixture agent', moving: true })
    await control({ action: 'key', key: 'Control+Alt+Escape' })
    assert.equal(stopped, 2, 'the global emergency shortcut stops access')
    assert.equal(halo.isVisible(), false)
  } finally { indicator.destroy() }
  console.log(JSON.stringify({ ok: true, platform: process.platform, checks: ['real cursor movement', 'click', 'Unicode typing', 'keyboard shortcut', 'screen capture', 'visible indicator', 'Stop all button', 'emergency shortcut'], imageSize: image.imageSize, bounds: image.bounds }))
}
run().then(() => { window?.destroy(); app.exit(0) }).catch(error => { console.error(error); window?.destroy(); app.exit(1) })
