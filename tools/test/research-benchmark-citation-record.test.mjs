// The citable artifact is the template, and its citation record carries three values
// instead of "Not declared": the author with the academic-form AI
// statement, the MIT licence covering the specification and every generated project, and
// no DOI, cited by template version and generator instead.
//
// The study's own spec.citation stays a SEPARATE layer. Naming the template's author as
// the author of every generated study would misattribute other people's work, so the two
// layers are asserted apart here.
import assert from 'node:assert/strict'
import test from 'node:test'
import { readFile } from 'node:fs/promises'
import { TEMPLATE, RUNTIME_FILES, bindRuntimeSources, freezeStudy, templateCitation } from '../../src/benchmark/study.mjs'
import { projectFiles } from '../../src/benchmark/export.mjs'
import { runStudy } from '../../src/benchmark/runner.mjs'
import { researchReportFiles } from '../../src/benchmark/report.mjs'
import { endpointStudy, FIXED_NOW } from './fixtures/research-benchmark-endpoints.mjs'

const baseline = JSON.parse(await readFile(new URL('./fixtures/research-benchmark-endpoints-baseline.json', import.meta.url), 'utf8'))
// docs/ATTRIBUTION.md, "## The academic form" (line 25), blockquote lines 29-32, verbatim
// with the quote markers stripped and the wrapped lines joined.
const AI_STATEMENT = 'Joshua Pinckard conceived the project, defined its objectives and requirements, directed the autonomous agent workflows, selected and evaluated outputs, and assumes responsibility for the research methodology and conclusions. AI agents generated substantial portions of the implementation and written drafts.'
const AUTHOR = 'Joshua Pinckard'
const unescapeMd = text => text.replace(/\\([\\`*_{}[\]()#+.!|<>])/g, '$1')
// WHY AN APPLICATION VERSION IS IN A CITATION AT ALL. The template has no DOI, so
// citeAs has to identify the artifact some other way, and the two things that fix it are
// the template version and the release that generated the study. That second part is
// provenance: a reader holding a report needs to know which application release froze and
// rendered it, because the runtime shipped inside it -- the compiler, the analysis and the
// report generator -- is that release's, and a later one may produce different numbers
// from the same specification.
//
// Derived, never retyped. package.json is the release's single source of truth, and both
// version constants are held equal to it by other suites
// (research-benchmark-generator-identity.test.mjs:36 for GENERATOR,
// research-benchmark-template-citation.test.mjs:61 for TEMPLATE.generator). Reading it
// here checks the chain reaches the citation instead of restating TEMPLATE.generator,
// which would be a tautology that passes however wrong the constant is. A literal would
// also go stale at every bump: 1.0.44 was pinned here and broke the moment the app moved
// to 1.0.45, which is the defect this comment replaces.
const APP_VERSION = JSON.parse(await readFile(new URL('../../package.json', import.meta.url), 'utf8')).version
const escapeRe = text => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

// endpointStudy takes DIGESTS; projectFiles takes the source TEXT and checks it against
// them. This branch changes pinned runtime files, so the fixture is rebound to the runtime
// actually running here rather than to the digests the baseline recorded.
const liveSources = async () => Object.fromEntries(await Promise.all(RUNTIME_FILES.map(async name =>
  [name, await readFile(new URL('../../src/benchmark/' + name, import.meta.url), 'utf8')])))
const frozen = async () => freezeStudy(await bindRuntimeSources(endpointStudy(baseline.runtimeSources), await liveSources()))

test('the template constants carry the author, the licence and the citation form, and no DOI is invented', () => {
  assert.equal(TEMPLATE.author, AUTHOR)
  assert.equal(TEMPLATE.aiStatement, AI_STATEMENT)
  assert.equal(TEMPLATE.license, 'MIT')
  assert.match(TEMPLATE.licenseCovers, /template specification and every project generated from it/)
  assert.equal(TEMPLATE.doi, null, 'no DOI, and no placeholder standing in for one')
  assert.match(TEMPLATE.citeAs, new RegExp(TEMPLATE.version))
  assert.match(TEMPLATE.citeAs, new RegExp('generated by ToolsEnabled ' + escapeRe(APP_VERSION)),
    'citeAs names the release that generated the study, because the template has no DOI to resolve to')
})

test('CITATION.cff names the template author, the licence and the AI statement, and emits no template DOI', async () => {
  const { cff } = await templateCitation(await frozen())
  assert.ok(cff.includes(AUTHOR), 'the template author is named in the citation file')
  assert.ok(cff.includes(AI_STATEMENT), 'the academic-form statement appears verbatim')
  assert.match(cff, /license: MIT/)
  assert.doesNotMatch(cff, /^doi:/m, 'no study-level DOI key, because there is no DOI')
  const templateRef = cff.split('references:')[1].split(/\n  - type: /)[1]
  assert.ok(/^software/.test(templateRef), 'the first reference is the template itself')
  assert.doesNotMatch(templateRef, /^\s*doi:/m, 'the template entry carries no DOI field')
  assert.doesNotMatch(templateRef, /10\.\d{4,}\//, 'and no placeholder DOI standing in for one')
  // Saying plainly that there is none is the point; the word appearing in that sentence is not a DOI.
  assert.match(templateRef, /No DOI is registered for the template/)
  // The method references keep their real DOIs; only the template has none.
  assert.match(cff, /10\.1080\/01621459\.1927\.10502953/, 'Wilson keeps its verified DOI')
})

test('CITATION.bib names the same three, in the template entry', async () => {
  const { bibtex } = await templateCitation(await frozen())
  const templateEntry = bibtex.split('@misc{')[0]
  assert.ok(templateEntry.includes(AUTHOR), 'the template entry names its author')
  assert.ok(templateEntry.includes(AI_STATEMENT), 'the academic-form statement appears verbatim')
  assert.match(templateEntry, /license = \{MIT\}/)
  assert.doesNotMatch(templateEntry, /doi = \{/, 'no DOI field for the template')
})

test('the study layer stays separate: the template author is not made the author of the study', async () => {
  const project = await frozen()
  const { cff, authors } = await templateCitation(project)
  // This fixture declares no spec.citation, so the study layer must still say so.
  assert.equal(project.spec.citation, undefined)
  assert.equal(authors.length, 1)
  assert.match(authors[0].name, /^Not declared/, 'the study keeps its own not-declared authors, not the template author')
  // The study block is the one before the references block; the template author belongs to the latter.
  const studyBlock = cff.split('references:')[0]
  assert.ok(!studyBlock.includes(AUTHOR), 'the template author must not appear as the study author')
})

test('the report distinguishes the template record from the study record', async () => {
  const project = await frozen()
  const result = await runStudy(project, { now: () => FIXED_NOW })
  const md = unescapeMd((await researchReportFiles(project, result.events))['report.md'])
  assert.match(md, /\| Template author \| Joshua Pinckard \|/)
  assert.match(md, /\| Template licence \| MIT/)
  assert.match(md, /\| Template DOI \| None/)
  assert.match(md, new RegExp('cite .*' + escapeRe(TEMPLATE.version) + '.*generated by ToolsEnabled ' + escapeRe(APP_VERSION)),
    'the report tells a citing reader both halves of the identity: the template version and the generating release')
  assert.ok(md.includes(AI_STATEMENT), 'the academic-form statement appears verbatim in the report')
  // The study's own declared fields stay their own rows.
  assert.match(md, /\| Declared DOI \|/)
})

test('the exported project ships a LICENSE naming MIT and what it covers', async () => {
  const files = await projectFiles(await frozen(), await liveSources(), {})
  const license = files['LICENSE']
  assert.equal(typeof license, 'string', 'the export ships a LICENSE file')
  assert.match(license, /MIT License/)
  assert.match(license, /Joshua Pinckard/)
  assert.match(license, /template specification and every project generated from it/)
  assert.match(files['README.md'], /MIT/, 'the README points at the licence')
})
